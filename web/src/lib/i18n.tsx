const dicts: Record<Lang, Dict> = { en, hi, mr }
export type Key = keyof Dict

type Ctx = { lang: Lang; setLang: (l: Lang) => void; t: (k: Key, vars?: Record<string, string | number>) => string }
const I18n = createContext<Ctx | null>(null)

function initialLang(): Lang {
  const saved = store.get('cd.lang')
  if (saved === 'en' || saved === 'hi' || saved === 'mr') return saved
  const nav = (navigator.language || 'en').toLowerCase()
  if (nav.startsWith('hi')) return 'hi'
  if (nav.startsWith('mr')) return 'mr'
  return 'en'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const value = useMemo<Ctx>(
    () => ({
      lang,
      setLang: (l) => {
        store.set('cd.lang', l)
        document.documentElement.lang = l
        setLangState(l)
      },
      t: (k, vars) => {
        let s: string = dicts[lang][k] ?? en[k]
        if (vars) for (const [name, v] of Object.entries(vars)) s = s.replaceAll(`{${name}}`, String(v))
        return s
      },
    }),
    [lang],
  )
  return <I18n.Provider value={value}>{children}</I18n.Provider>
}

export function useI18n(): Ctx {
  const ctx = useContext(I18n)
  if (!ctx) throw new Error('I18nProvider missing')
  return ctx
}
